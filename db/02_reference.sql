-- =============================================================================
-- 02  Reference / lookup tables
-- =============================================================================

CREATE TABLE currencies (
    currency_code  CHAR(3)      PRIMARY KEY CHECK (currency_code ~ '^[A-Z]{3}$'),   -- ISO 4217
    name           VARCHAR(64)  NOT NULL,
    symbol         VARCHAR(8)   NOT NULL,
    minor_units    SMALLINT     NOT NULL DEFAULT 2 CHECK (minor_units BETWEEN 0 AND 4)  -- decimals (JPY = 0)
);
COMMENT ON TABLE currencies IS 'All money in this database is stored as integers in the currency''s minor unit (e.g. cents).';

CREATE TABLE countries (
    country_code      CHAR(2)       PRIMARY KEY CHECK (country_code ~ '^[A-Z]{2}$'),  -- ISO 3166-1 alpha-2
    name              VARCHAR(100)  NOT NULL UNIQUE,
    default_currency  CHAR(3)       NOT NULL REFERENCES currencies
);

CREATE TABLE languages (
    language_code  VARCHAR(10)  PRIMARY KEY,           -- IETF tag: en, bg, zh-CN ...
    name           VARCHAR(64)  NOT NULL UNIQUE,
    native_name    VARCHAR(64)  NOT NULL
);

CREATE TABLE platforms (
    platform_id  SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         VARCHAR(16)  NOT NULL UNIQUE,         -- windows, macos, linux, steamdeck
    name         VARCHAR(64)  NOT NULL
);

CREATE TABLE genres (
    genre_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(64) NOT NULL UNIQUE
);

CREATE TABLE tags (
    tag_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(64) NOT NULL UNIQUE
);
