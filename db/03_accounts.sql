-- =============================================================================
-- 03  Accounts, profiles, friends, groups, chat
-- =============================================================================

CREATE TABLE users (
    user_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username           CITEXT          NOT NULL UNIQUE CHECK (username ~ '^[A-Za-z0-9_]{3,32}$'),
    email              CITEXT          NOT NULL UNIQUE CHECK (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    password_hash      TEXT            NOT NULL,           -- never store plaintext passwords
    country_code       CHAR(2)         NOT NULL REFERENCES countries,
    status             account_status  NOT NULL DEFAULT 'active',
    steam_level        INT             NOT NULL DEFAULT 0 CHECK (steam_level >= 0),
    xp                 INT             NOT NULL DEFAULT 0 CHECK (xp >= 0),
    two_factor_enabled BOOLEAN         NOT NULL DEFAULT FALSE,
    email_verified_at  TIMESTAMPTZ,
    last_login_at      TIMESTAMPTZ,
    created_at         TIMESTAMPTZ     NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ     NOT NULL DEFAULT now()
);

CREATE TABLE user_profiles (
    user_id         BIGINT              PRIMARY KEY REFERENCES users ON DELETE CASCADE,
    display_name    VARCHAR(64)         NOT NULL,
    real_name       VARCHAR(100),
    bio             TEXT,
    avatar_url      TEXT,
    background_url  TEXT,
    visibility      profile_visibility  NOT NULL DEFAULT 'public',
    created_at      TIMESTAMPTZ         NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ         NOT NULL DEFAULT now()
);

-- One wallet per user, in a single currency (the currency of the user's country at signup).
CREATE TABLE user_wallets (
    user_id        BIGINT       PRIMARY KEY REFERENCES users ON DELETE CASCADE,
    currency_code  CHAR(3)      NOT NULL REFERENCES currencies,
    balance_minor  BIGINT       NOT NULL DEFAULT 0 CHECK (balance_minor >= 0),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Only a hash of the session token is stored, so a database leak does not leak live sessions.
CREATE TABLE user_sessions (
    session_id   UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id      BIGINT       NOT NULL REFERENCES users ON DELETE CASCADE,
    token_hash   BYTEA        NOT NULL UNIQUE,              -- sha256 of the token handed to the client
    ip_address   INET,
    user_agent   TEXT,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expires_at   TIMESTAMPTZ  NOT NULL,
    revoked_at   TIMESTAMPTZ,
    CHECK (expires_at > created_at)
);

CREATE TABLE user_bans (
    ban_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users ON DELETE CASCADE,
    ban_type   ban_type     NOT NULL,
    reason     TEXT         NOT NULL,
    issued_by  BIGINT       REFERENCES users ON DELETE SET NULL,
    issued_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ,                                 -- NULL = permanent
    CHECK (expires_at IS NULL OR expires_at > issued_at)
);

-- Friendship is stored once per pair; the lower user_id is always first.
CREATE TABLE friendships (
    user_id_low   BIGINT       NOT NULL REFERENCES users ON DELETE CASCADE,
    user_id_high  BIGINT       NOT NULL REFERENCES users ON DELETE CASCADE,
    since         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id_low, user_id_high),
    CHECK (user_id_low < user_id_high)
);

CREATE TABLE friend_requests (
    request_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id     BIGINT          NOT NULL REFERENCES users ON DELETE CASCADE,
    receiver_id   BIGINT          NOT NULL REFERENCES users ON DELETE CASCADE,
    status        request_status  NOT NULL DEFAULT 'pending',
    created_at    TIMESTAMPTZ     NOT NULL DEFAULT now(),
    responded_at  TIMESTAMPTZ,
    CHECK (sender_id <> receiver_id)
);
-- at most one pending request per pair, regardless of direction
CREATE UNIQUE INDEX uq_friend_requests_pending
    ON friend_requests (LEAST(sender_id, receiver_id), GREATEST(sender_id, receiver_id))
    WHERE status = 'pending';

CREATE TABLE user_blocks (
    blocker_id  BIGINT       NOT NULL REFERENCES users ON DELETE CASCADE,
    blocked_id  BIGINT       NOT NULL REFERENCES users ON DELETE CASCADE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PRIMARY KEY (blocker_id, blocked_id),
    CHECK (blocker_id <> blocked_id)
);

CREATE TABLE chat_messages (
    message_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id    BIGINT       NOT NULL REFERENCES users ON DELETE CASCADE,
    receiver_id  BIGINT       NOT NULL REFERENCES users ON DELETE CASCADE,
    body         TEXT         NOT NULL CHECK (length(body) BETWEEN 1 AND 4000),
    sent_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    read_at      TIMESTAMPTZ,
    CHECK (sender_id <> receiver_id)
);

CREATE TABLE groups (
    group_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(100)  NOT NULL UNIQUE,
    tag          VARCHAR(8)    NOT NULL UNIQUE,
    description  TEXT,
    owner_id     BIGINT        NOT NULL REFERENCES users ON DELETE RESTRICT,
    is_public    BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE TABLE group_members (
    group_id   BIGINT       NOT NULL REFERENCES groups ON DELETE CASCADE,
    user_id    BIGINT       NOT NULL REFERENCES users ON DELETE CASCADE,
    role       group_role   NOT NULL DEFAULT 'member',
    joined_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PRIMARY KEY (group_id, user_id)
);
-- exactly one owner per group (the owner row is kept in sync with groups.owner_id by trigger)
CREATE UNIQUE INDEX uq_group_single_owner ON group_members (group_id) WHERE role = 'owner';
