-- =============================================================================
-- 04  Store catalog: companies, apps (games / DLC / software), metadata, prices
-- =============================================================================

CREATE TABLE companies (
    company_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(150)  NOT NULL UNIQUE,
    website_url   TEXT,
    country_code  CHAR(2)       REFERENCES countries,
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- "App" is Steam's word for anything sold in the store: game, DLC, demo, software, soundtrack...
CREATE TABLE apps (
    app_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_app_id      BIGINT        REFERENCES apps ON DELETE CASCADE,   -- base game for DLC / demo / soundtrack
    app_type           app_type      NOT NULL DEFAULT 'game',
    name               VARCHAR(200)  NOT NULL,
    slug               VARCHAR(220)  NOT NULL UNIQUE,
    short_description  VARCHAR(500),
    about              TEXT,
    status             app_status    NOT NULL DEFAULT 'unreleased',
    release_date       DATE,
    is_free            BOOLEAN       NOT NULL DEFAULT FALSE,
    age_rating         SMALLINT      CHECK (age_rating IN (0, 3, 7, 12, 16, 18)),
    metacritic_score   SMALLINT      CHECK (metacritic_score BETWEEN 0 AND 100),
    website_url        TEXT,
    positive_reviews   INT           NOT NULL DEFAULT 0 CHECK (positive_reviews >= 0),   -- maintained by trigger
    negative_reviews   INT           NOT NULL DEFAULT 0 CHECK (negative_reviews >= 0),   -- maintained by trigger
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CHECK (parent_app_id IS NULL OR parent_app_id <> app_id),
    CHECK (app_type NOT IN ('dlc', 'demo', 'soundtrack') OR parent_app_id IS NOT NULL)
);

CREATE TABLE app_developers (
    app_id      BIGINT NOT NULL REFERENCES apps      ON DELETE CASCADE,
    company_id  BIGINT NOT NULL REFERENCES companies ON DELETE RESTRICT,
    PRIMARY KEY (app_id, company_id)
);

CREATE TABLE app_publishers (
    app_id      BIGINT NOT NULL REFERENCES apps      ON DELETE CASCADE,
    company_id  BIGINT NOT NULL REFERENCES companies ON DELETE RESTRICT,
    PRIMARY KEY (app_id, company_id)
);

CREATE TABLE app_genres (
    app_id      BIGINT   NOT NULL REFERENCES apps   ON DELETE CASCADE,
    genre_id    INT      NOT NULL REFERENCES genres ON DELETE CASCADE,
    is_primary  BOOLEAN  NOT NULL DEFAULT FALSE,
    PRIMARY KEY (app_id, genre_id)
);
CREATE UNIQUE INDEX uq_app_primary_genre ON app_genres (app_id) WHERE is_primary;

CREATE TABLE app_tags (
    app_id    BIGINT  NOT NULL REFERENCES apps ON DELETE CASCADE,
    tag_id    INT     NOT NULL REFERENCES tags ON DELETE CASCADE,
    votes     INT     NOT NULL DEFAULT 0 CHECK (votes >= 0),     -- user-voted relevance
    PRIMARY KEY (app_id, tag_id)
);

CREATE TABLE app_platforms (
    app_id       BIGINT    NOT NULL REFERENCES apps      ON DELETE CASCADE,
    platform_id  SMALLINT  NOT NULL REFERENCES platforms ON DELETE CASCADE,
    PRIMARY KEY (app_id, platform_id)
);

CREATE TABLE app_languages (
    app_id          BIGINT       NOT NULL REFERENCES apps      ON DELETE CASCADE,
    language_code   VARCHAR(10)  NOT NULL REFERENCES languages ON DELETE CASCADE,
    has_interface   BOOLEAN      NOT NULL DEFAULT TRUE,
    has_full_audio  BOOLEAN      NOT NULL DEFAULT FALSE,
    has_subtitles   BOOLEAN      NOT NULL DEFAULT FALSE,
    PRIMARY KEY (app_id, language_code)
);

CREATE TABLE system_requirements (
    app_id       BIGINT            NOT NULL REFERENCES apps      ON DELETE CASCADE,
    platform_id  SMALLINT          NOT NULL REFERENCES platforms ON DELETE CASCADE,
    tier         requirement_tier  NOT NULL,
    os           VARCHAR(100),
    processor    VARCHAR(150),
    memory_mb    INT               CHECK (memory_mb > 0),
    graphics     VARCHAR(150),
    storage_mb   INT               CHECK (storage_mb > 0),
    notes        TEXT,
    PRIMARY KEY (app_id, platform_id, tier)
);

CREATE TABLE app_media (
    media_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id      BIGINT      NOT NULL REFERENCES apps ON DELETE CASCADE,
    media_type  media_type  NOT NULL,
    url         TEXT        NOT NULL,
    sort_order  SMALLINT    NOT NULL DEFAULT 0
);

-- Regional price history. The row with valid_to IS NULL is the current list price.
CREATE TABLE app_prices (
    app_id         BIGINT       NOT NULL REFERENCES apps       ON DELETE CASCADE,
    currency_code  CHAR(3)      NOT NULL REFERENCES currencies,
    price_minor    BIGINT       NOT NULL CHECK (price_minor >= 0),
    valid_from     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    valid_to       TIMESTAMPTZ,
    PRIMARY KEY (app_id, currency_code, valid_from),
    CHECK (valid_to IS NULL OR valid_to > valid_from),
    -- two price periods for the same app and currency may never overlap
    EXCLUDE USING gist (app_id WITH =, currency_code WITH =, tstzrange(valid_from, valid_to) WITH &&)
);
CREATE UNIQUE INDEX uq_app_prices_current ON app_prices (app_id, currency_code) WHERE valid_to IS NULL;

CREATE TABLE achievements (
    achievement_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id          BIGINT        NOT NULL REFERENCES apps ON DELETE CASCADE,
    api_name        VARCHAR(100)  NOT NULL,
    name            VARCHAR(150)  NOT NULL,
    description     TEXT,
    icon_url        TEXT,
    is_hidden       BOOLEAN       NOT NULL DEFAULT FALSE,
    points          SMALLINT      NOT NULL DEFAULT 10 CHECK (points > 0),
    UNIQUE (app_id, api_name)
);

CREATE TABLE bundles (
    bundle_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(150)  NOT NULL UNIQUE,
    description   TEXT,
    discount_pct  SMALLINT      NOT NULL CHECK (discount_pct BETWEEN 1 AND 90),
    is_active     BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE TABLE bundle_apps (
    bundle_id  BIGINT NOT NULL REFERENCES bundles ON DELETE CASCADE,
    app_id     BIGINT NOT NULL REFERENCES apps    ON DELETE CASCADE,
    PRIMARY KEY (bundle_id, app_id)
);
