-- =============================================================================
-- 05  Store: sales, wishlist, cart, orders, payments, wallet, keys, refunds
-- =============================================================================

CREATE TABLE sales (
    sale_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(150)  NOT NULL,
    starts_at  TIMESTAMPTZ   NOT NULL,
    ends_at    TIMESTAMPTZ   NOT NULL,
    CHECK (ends_at > starts_at)
);

CREATE TABLE sale_apps (
    sale_id       BIGINT    NOT NULL REFERENCES sales ON DELETE CASCADE,
    app_id        BIGINT    NOT NULL REFERENCES apps  ON DELETE CASCADE,
    discount_pct  SMALLINT  NOT NULL CHECK (discount_pct BETWEEN 1 AND 100),
    PRIMARY KEY (sale_id, app_id)
);

CREATE TABLE wishlists (
    user_id   BIGINT       NOT NULL REFERENCES users ON DELETE CASCADE,
    app_id    BIGINT       NOT NULL REFERENCES apps  ON DELETE CASCADE,
    added_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    priority  INT          NOT NULL DEFAULT 0,
    PRIMARY KEY (user_id, app_id)
);

CREATE TABLE cart_items (
    user_id   BIGINT       NOT NULL REFERENCES users ON DELETE CASCADE,
    app_id    BIGINT       NOT NULL REFERENCES apps  ON DELETE CASCADE,
    added_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, app_id)
);

-- Only a provider token and display info are stored here; never raw card numbers.
CREATE TABLE payment_methods (
    payment_method_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT            NOT NULL REFERENCES users ON DELETE CASCADE,
    provider           payment_provider  NOT NULL,
    provider_token     TEXT              NOT NULL,
    label              VARCHAR(100),
    card_last4         CHAR(4),
    expires_month      SMALLINT          CHECK (expires_month BETWEEN 1 AND 12),
    expires_year       SMALLINT,
    is_default         BOOLEAN           NOT NULL DEFAULT FALSE,
    created_at         TIMESTAMPTZ       NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_payment_methods_default ON payment_methods (user_id) WHERE is_default;

CREATE TABLE orders (
    order_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT        NOT NULL REFERENCES users ON DELETE RESTRICT,
    gift_recipient_id   BIGINT        REFERENCES users ON DELETE RESTRICT,   -- NULL = bought for self
    currency_code       CHAR(3)       NOT NULL REFERENCES currencies,
    subtotal_minor      BIGINT        NOT NULL DEFAULT 0 CHECK (subtotal_minor >= 0),
    discount_minor      BIGINT        NOT NULL DEFAULT 0 CHECK (discount_minor >= 0),
    tax_minor           BIGINT        NOT NULL DEFAULT 0 CHECK (tax_minor >= 0),
    total_minor         BIGINT        NOT NULL DEFAULT 0 CHECK (total_minor >= 0),
    wallet_used_minor   BIGINT        NOT NULL DEFAULT 0 CHECK (wallet_used_minor >= 0),
    payment_method_id   BIGINT        REFERENCES payment_methods ON DELETE SET NULL,
    status              order_status  NOT NULL DEFAULT 'pending',
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    completed_at        TIMESTAMPTZ,
    CHECK (total_minor = subtotal_minor - discount_minor + tax_minor),
    CHECK (wallet_used_minor <= total_minor),
    CHECK (gift_recipient_id IS NULL OR gift_recipient_id <> user_id)
);

CREATE TABLE order_items (
    order_item_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id            BIGINT    NOT NULL REFERENCES orders  ON DELETE CASCADE,
    app_id              BIGINT    NOT NULL REFERENCES apps    ON DELETE RESTRICT,
    bundle_id           BIGINT    REFERENCES bundles          ON DELETE SET NULL,
    list_price_minor    BIGINT    NOT NULL CHECK (list_price_minor >= 0),
    discount_pct        SMALLINT  NOT NULL DEFAULT 0 CHECK (discount_pct BETWEEN 0 AND 100),
    final_price_minor   BIGINT    NOT NULL CHECK (final_price_minor >= 0),
    refunded_at         TIMESTAMPTZ,
    UNIQUE (order_id, app_id),
    CHECK (final_price_minor <= list_price_minor)
);

CREATE TABLE wallet_transactions (
    txn_id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT           NOT NULL REFERENCES users ON DELETE RESTRICT,
    txn_type             wallet_txn_type  NOT NULL,
    amount_minor         BIGINT           NOT NULL CHECK (amount_minor <> 0),   -- + credit / - debit
    currency_code        CHAR(3)          NOT NULL REFERENCES currencies,
    balance_after_minor  BIGINT           NOT NULL,                             -- filled in by trigger
    order_id             BIGINT           REFERENCES orders ON DELETE SET NULL,
    note                 TEXT,
    created_at           TIMESTAMPTZ      NOT NULL DEFAULT now()
);

CREATE TABLE wallet_codes (
    code           VARCHAR(32)  PRIMARY KEY,
    currency_code  CHAR(3)      NOT NULL REFERENCES currencies,
    amount_minor   BIGINT       NOT NULL CHECK (amount_minor > 0),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    redeemed_by    BIGINT       REFERENCES users ON DELETE SET NULL,
    redeemed_at    TIMESTAMPTZ,
    CHECK ((redeemed_by IS NULL) = (redeemed_at IS NULL))
);

CREATE TABLE game_keys (
    key_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id       BIGINT       NOT NULL REFERENCES apps ON DELETE CASCADE,
    key_code     VARCHAR(32)  NOT NULL UNIQUE,
    status       key_status   NOT NULL DEFAULT 'available',
    company_id   BIGINT       REFERENCES companies ON DELETE SET NULL,   -- who issued the key
    redeemed_by  BIGINT       REFERENCES users ON DELETE SET NULL,
    redeemed_at  TIMESTAMPTZ,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CHECK ((status = 'redeemed') = (redeemed_at IS NOT NULL))
);

CREATE TABLE refunds (
    refund_id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id               BIGINT         NOT NULL REFERENCES order_items ON DELETE CASCADE,
    user_id                     BIGINT         NOT NULL REFERENCES users ON DELETE RESTRICT,
    reason                      TEXT,
    status                      refund_status  NOT NULL DEFAULT 'pending',
    amount_minor                BIGINT         CHECK (amount_minor >= 0),      -- defaults to the item's paid price
    playtime_minutes_at_request INT            NOT NULL DEFAULT 0,
    requested_at                TIMESTAMPTZ    NOT NULL DEFAULT now(),
    processed_at                TIMESTAMPTZ,
    CHECK ((status = 'pending') = (processed_at IS NULL))
);
-- one open or approved refund per item; a denied request may be filed again
CREATE UNIQUE INDEX uq_refunds_active_item ON refunds (order_item_id) WHERE status IN ('pending', 'approved');
