-- 06  Library, playtime, achievements
-- =============================================================================

CREATE TABLE library_entries (
    user_id                 BIGINT            NOT NULL REFERENCES users ON DELETE CASCADE,
    app_id                  BIGINT            NOT NULL REFERENCES apps  ON DELETE CASCADE,
    source                  ownership_source  NOT NULL,
    order_item_id           BIGINT            REFERENCES order_items ON DELETE SET NULL,
    key_id                  BIGINT            REFERENCES game_keys   ON DELETE SET NULL,
    acquired_at             TIMESTAMPTZ       NOT NULL DEFAULT now(),
    is_hidden               BOOLEAN           NOT NULL DEFAULT FALSE,
    is_favorite             BOOLEAN           NOT NULL DEFAULT FALSE,
    total_playtime_minutes  INT               NOT NULL DEFAULT 0 CHECK (total_playtime_minutes >= 0),  -- maintained by trigger
    last_played_at          TIMESTAMPTZ,
    PRIMARY KEY (user_id, app_id)
);

CREATE TABLE playtime_sessions (
    session_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT       NOT NULL,
    app_id            BIGINT       NOT NULL,
    platform_id       SMALLINT     NOT NULL REFERENCES platforms,
    started_at        TIMESTAMPTZ  NOT NULL,
    ended_at          TIMESTAMPTZ  NOT NULL,
    duration_minutes  INT          NOT NULL DEFAULT 0 CHECK (duration_minutes >= 0),   -- computed by trigger
    FOREIGN KEY (user_id, app_id) REFERENCES library_entries ON DELETE CASCADE,
    CHECK (ended_at >= started_at)
);

CREATE TABLE user_achievements (
    user_id         BIGINT       NOT NULL REFERENCES users        ON DELETE CASCADE,
    achievement_id  BIGINT       NOT NULL REFERENCES achievements ON DELETE CASCADE,
    unlocked_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, achievement_id)
);
