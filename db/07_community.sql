-- =============================================================================
-- 07  Community: reviews, discussions, workshop
-- =============================================================================

CREATE TABLE reviews (
    review_id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                        BIGINT       NOT NULL REFERENCES users ON DELETE CASCADE,
    app_id                         BIGINT       NOT NULL REFERENCES apps  ON DELETE CASCADE,
    is_recommended                 BOOLEAN      NOT NULL,
    body                           TEXT         NOT NULL CHECK (length(body) >= 1),
    playtime_at_review_minutes     INT          NOT NULL DEFAULT 0,     -- snapshot, set by trigger
    is_visible                     BOOLEAN      NOT NULL DEFAULT TRUE,
    votes_helpful                  INT          NOT NULL DEFAULT 0,     -- maintained by trigger
    votes_funny                    INT          NOT NULL DEFAULT 0,     -- maintained by trigger
    created_at                     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at                     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    UNIQUE (user_id, app_id)
);

CREATE TABLE review_votes (
    review_id   BIGINT       NOT NULL REFERENCES reviews ON DELETE CASCADE,
    user_id     BIGINT       NOT NULL REFERENCES users   ON DELETE CASCADE,
    vote        vote_type    NOT NULL,
    voted_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PRIMARY KEY (review_id, user_id, vote)
);

CREATE TABLE review_comments (
    comment_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id   BIGINT       NOT NULL REFERENCES reviews ON DELETE CASCADE,
    user_id     BIGINT       NOT NULL REFERENCES users   ON DELETE CASCADE,
    body        TEXT         NOT NULL CHECK (length(body) BETWEEN 1 AND 2000),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE discussion_threads (
    thread_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id      BIGINT        NOT NULL REFERENCES apps  ON DELETE CASCADE,
    author_id   BIGINT        NOT NULL REFERENCES users ON DELETE CASCADE,
    title       VARCHAR(200)  NOT NULL,
    is_pinned   BOOLEAN       NOT NULL DEFAULT FALSE,
    is_locked   BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE TABLE discussion_posts (
    post_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thread_id   BIGINT       NOT NULL REFERENCES discussion_threads ON DELETE CASCADE,
    author_id   BIGINT       NOT NULL REFERENCES users              ON DELETE CASCADE,
    body        TEXT         NOT NULL CHECK (length(body) >= 1),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE workshop_items (
    item_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id       BIGINT        NOT NULL REFERENCES apps  ON DELETE CASCADE,
    author_id    BIGINT        NOT NULL REFERENCES users ON DELETE CASCADE,
    title        VARCHAR(200)  NOT NULL,
    description  TEXT,
    file_url     TEXT          NOT NULL,
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- In-client notifications; rows are written by triggers (gift received, trade offer, item sold ...).
CREATE TABLE notifications (
    notification_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT             NOT NULL REFERENCES users ON DELETE CASCADE,
    type             notification_type  NOT NULL,
    payload          JSONB              NOT NULL DEFAULT '{}'::jsonb,
    created_at       TIMESTAMPTZ        NOT NULL DEFAULT now(),
    read_at          TIMESTAMPTZ
);

CREATE TABLE workshop_subscriptions (
    user_id        BIGINT       NOT NULL REFERENCES users          ON DELETE CASCADE,
    item_id        BIGINT       NOT NULL REFERENCES workshop_items ON DELETE CASCADE,
    subscribed_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, item_id)
);
