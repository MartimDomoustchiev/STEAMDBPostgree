CREATE TABLE item_definitions (
    item_def_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id         BIGINT        NOT NULL REFERENCES apps ON DELETE CASCADE,
    name           VARCHAR(150)  NOT NULL,
    item_type      item_type     NOT NULL,
    rarity         item_rarity   NOT NULL DEFAULT 'common',
    is_tradable    BOOLEAN       NOT NULL DEFAULT TRUE,
    is_marketable  BOOLEAN       NOT NULL DEFAULT TRUE,
    icon_url       TEXT,
    UNIQUE (app_id, name)
);

CREATE TABLE inventory_items (
    inventory_item_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_def_id        BIGINT       NOT NULL REFERENCES item_definitions ON DELETE RESTRICT,
    owner_id           BIGINT       NOT NULL REFERENCES users            ON DELETE CASCADE,
    acquired_via       VARCHAR(20)  NOT NULL DEFAULT 'drop' CHECK (acquired_via IN ('drop', 'craft', 'trade', 'market', 'gift', 'promo')),
    acquired_at        TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE trade_offers (
    trade_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id     BIGINT        NOT NULL REFERENCES users ON DELETE CASCADE,
    receiver_id   BIGINT        NOT NULL REFERENCES users ON DELETE CASCADE,
    status        trade_status  NOT NULL DEFAULT 'pending',
    message       TEXT,
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    responded_at  TIMESTAMPTZ,
    CHECK (sender_id <> receiver_id)
);

-- Each item is owned by either the sender (offered) or the receiver (requested); ownership at
-- accept time decides the direction, so no direction column is needed.
CREATE TABLE trade_offer_items (
    trade_id           BIGINT NOT NULL REFERENCES trade_offers    ON DELETE CASCADE,
    inventory_item_id  BIGINT NOT NULL REFERENCES inventory_items ON DELETE CASCADE,
    PRIMARY KEY (trade_id, inventory_item_id)
);

CREATE TABLE market_listings (
    listing_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_item_id  BIGINT          NOT NULL REFERENCES inventory_items ON DELETE CASCADE,
    seller_id          BIGINT          NOT NULL REFERENCES users           ON DELETE CASCADE,
    buyer_id           BIGINT          REFERENCES users                    ON DELETE SET NULL,
    currency_code      CHAR(3)         NOT NULL REFERENCES currencies,
    price_minor        BIGINT          NOT NULL CHECK (price_minor >= 3),     -- minimum listing price
    fee_minor          BIGINT          CHECK (fee_minor >= 0),                -- set when sold
    status             listing_status  NOT NULL DEFAULT 'active',
    listed_at          TIMESTAMPTZ     NOT NULL DEFAULT now(),
    sold_at            TIMESTAMPTZ,
    CHECK (buyer_id IS NULL OR buyer_id <> seller_id),
    CHECK ((status = 'sold') = (sold_at IS NOT NULL))
);
-- an item can only have one active listing at a time
CREATE UNIQUE INDEX uq_market_active_item ON market_listings (inventory_item_id) WHERE status = 'active';
